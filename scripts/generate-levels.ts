function generateBlueprint(blueprint: Blueprint): Board {
  const chapter = CHAPTERS[Math.floor(blueprint.index / 4)];
  if (!chapter) {
    throw new Error(`No chapter for level ${blueprint.index + 1}`);
  }
  const profile = CHAPTER_GENERATION[chapter.id];
  const board = generateBoard({
    ...profile,
    seed: blueprint.seed,
    width: chapter.width,
    height: chapter.height,
    targetPieces: blueprint.targetPieces,
  });
  if (!board) {
    throw new Error(
      `Could not generate level ${blueprint.index + 1} (${blueprint.title}) from seed ${blueprint.seed}`,
    );
  }
  return board;
}

const boards = BLUEPRINTS.map((blueprint) => ({
  blueprint,
  board: generateBlueprint(blueprint),
}));

const specs = boards.map(({ blueprint, board }) => {
  const level = makeLevel(
    blueprint.index,
    blueprint.title,
    blueprint.constellationId,
    blueprint.seed,
    board,
  );
  return level;
});

function formatPath(path: readonly { readonly x: number; readonly y: number }[]): string {
  return `[${path.map((cell) => `{ x: ${cell.x}, y: ${cell.y} }`).join(', ')}]`;
}

function formatBoard(board: Board): string {
  const pieces = board.pieces
    .map(
      (piece) => `        {
          id: ${JSON.stringify(piece.id)},
          path: ${formatPath(piece.path)},
          heading: ${JSON.stringify(piece.heading)},
          color: ${JSON.stringify(piece.color)},
        }`,
    )
    .join(',\n');
  return `{
      width: ${board.width},
      height: ${board.height},
      pieces: [
${pieces}
      ],
    }`;
}

